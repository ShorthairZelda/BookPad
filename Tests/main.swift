import Foundation
func check(_ condition: Bool, _ name: String) {
    if !condition { fatalError("FAIL: \(name)") }
    print("PASS: \(name)")
}
var gate = StickGate()
check(gate.update(x: 1, y: 0) == nil, "Held at startup does not turn page")
check(gate.update(x: 0, y: 0) == nil, "Center arms gate")
check(gate.update(x: -0.7, y: 0) == -1, "Left gesture")
check(gate.update(x: -1, y: 0) == nil, "Holding does not repeat")
check(gate.update(x: -0.4, y: 0) == nil, "Threshold jitter does not rearm")
check(gate.update(x: 1, y: 0) == nil, "Crossing directly does not repeat")
_ = gate.update(x: 0.1, y: 0.1)
check(gate.update(x: 0.8, y: 0) == 1, "Recenter then right gesture")
_ = gate.update(x: 0, y: 0)
check(gate.update(x: 0.7, y: 0.9) == nil, "Vertical dominant gesture ignored")
check(gate.update(x: 0.2, y: 0.8) == nil, "Vertical input ignored")
_ = gate.update(x: 0, y: 0)
check(gate.update(x: .nan, y: 0) == nil, "Invalid input disarms")
check(gate.update(x: 1, y: 0) == nil, "Must center after invalid input")
print("11 gesture checks passed")
var button = ButtonGate()
check(!button.update(pressed: true), "Button held at startup is ignored")
check(!button.update(pressed: false), "Button release does not act")
check(button.update(pressed: true), "Button press acts once")
check(!button.update(pressed: true), "Button holding does not repeat")
_ = button.update(pressed: false)
check(button.update(pressed: true), "Button release rearms")
var trigger = TriggerGate()
check(!trigger.update(value: 1), "Trigger held at startup ignored")
_ = trigger.update(value: 0)
check(!trigger.update(value: 0.5), "Shallow trigger press ignored")
check(trigger.update(value: 0.7), "Deep trigger press acts")
check(!trigger.update(value: 0.9), "Held trigger cannot repeat")
check(!trigger.update(value: 0.4), "Trigger jitter does not rearm")
check(!trigger.update(value: 0.7), "Second deep press requires release")
_ = trigger.update(value: 0.1)
check(trigger.update(value: 0.8), "Released trigger rearms")
var vertical = StickGate()
_ = vertical.updateDirection(x: 0, y: 0)
check(vertical.updateDirection(x: 0.05, y: 0.8) == .up, "Vertical stick gesture")
check(vertical.updateDirection(x: 0.8, y: 0) == nil, "One action per stick gesture across axes")
_ = vertical.updateDirection(x: 0, y: 0)
check(vertical.updateDirection(x: 0.8, y: 0.8) == nil, "Ambiguous diagonal is ignored")
check(vertical.updateDirection(x: 0.9, y: 0.4) == .right, "Dominant axis resolves diagonal")
check(ReadingAction.previousPage.reversed(true) == .nextPage, "Page reversal")
check(ReadingAction.nextChapter.reversed(true) == .previousChapter, "Chapter reversal")
check(ReadingAction.largerFont.reversed(true) == .largerFont, "Font action unaffected by reversal")
check(ReadingAction.allCases.filter { $0 != .pause }.allSatisfy { $0.shortcut != nil }, "Every reading action has a shortcut")
check(ReadingAction.confirm.shortcut!.key == 36 && ReadingAction.cancel.shortcut!.key == 53, "Confirm and cancel are Return and Escape")
print("32 checks passed")
